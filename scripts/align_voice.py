"""Align an external narration (e.g. ElevenLabs export) to a script, sentence by sentence.

Usage: python3 align_voice.py <script_module> <narration.wav> <timing_ts_out> <TS_DURATION_NAME> [lead_in] [tail]

The narration is split at its pauses (ffmpeg silencedetect); dynamic programming
picks one boundary per sentence so that every segment's length matches the
sentence's length in characters as closely as possible. Writes the same
timing.ts format as the TTS scripts (LINES with start/end, duration).
"""
import importlib
import json
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

mod, wav, ts_out, dur_name = sys.argv[1:5]
lead_in = float(sys.argv[5]) if len(sys.argv) > 5 else 0.0
tail = float(sys.argv[6]) if len(sys.argv) > 6 else 4.0
SCRIPT = importlib.import_module(mod).SCRIPT

total = float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", wav], capture_output=True, text=True).stdout)
log = subprocess.run(["ffmpeg", "-i", wav, "-af", "silencedetect=noise=-35dB:d=0.18", "-f", "null", "-"], capture_output=True, text=True).stderr
starts = [float(x) for x in re.findall(r"silence_start: ([0-9.]+)", log)]
ends = [float(x) for x in re.findall(r"silence_end: ([0-9.]+)", log)]
sil = list(zip(starts, ends))
# speech start / end
speech_start = sil[0][1] if sil and sil[0][0] < 0.05 else 0.0
speech_end = sil[-1][0] if sil and sil[-1][1] > total - 0.05 else total
# candidate cut points: middle of internal pauses, with pause length as a bonus
cands = [((a + b) / 2, b - a, a, b) for a, b in sil if a > speech_start + 0.1 and b < speech_end - 0.1]
n = len(SCRIPT)
lens = [len(re.sub(r"[\s،.؟:!]", "", pl)) for _, pl, _ in SCRIPT]
speech = speech_end - speech_start
expect = [speech * L / sum(lens) for L in lens]

# DP over candidates: choose n-1 cut points in order
INF = 1e18
m = len(cands)
pts = [speech_start] + [c[0] for c in cands] + [speech_end]
gap = [0.0] + [c[1] for c in cands] + [0.0]
# cost[i][j]: first i sentences end at point j
cost = [[INF] * (m + 2) for _ in range(n + 1)]
back = [[-1] * (m + 2) for _ in range(n + 1)]
cost[0][0] = 0.0
for i in range(1, n + 1):
    for j in range(1, m + 2):
        if i < n and j == m + 1:
            continue
        if i == n and j != m + 1:
            continue
        best, arg = INF, -1
        for k in range(0, j):
            if cost[i - 1][k] >= INF:
                continue
            d = pts[j] - pts[k]
            e = expect[i - 1]
            c = cost[i - 1][k] + ((d - e) / e) ** 2 - (0.6 * min(gap[j], 1.0) if j <= m else 0)
            if c < best:
                best, arg = c, k
        cost[i][j], back[i][j] = best, arg
cuts = []
j = m + 1
for i in range(n, 0, -1):
    cuts.append(j)
    j = back[i][j]
cuts.reverse()
bounds = [speech_start] + [pts[j] for j in cuts]
timing = []
for i, (section, plain, _) in enumerate(SCRIPT):
    a, b = bounds[i], bounds[i + 1]
    # trim the pause halves back off each sentence
    for s0, s1 in sil:
        if abs((s0 + s1) / 2 - a) < 1e-6:
            a = s1
        if abs((s0 + s1) / 2 - b) < 1e-6:
            b = s0
    timing.append({"i": i, "section": section, "text": plain, "start": round(a + lead_in, 3), "end": round(b + lead_in, 3)})

with open(ts_out, "w") as f:
    f.write("// Generated by scripts/align_voice.py - timing of the external narration (seconds).\n")
    f.write(f"export const {dur_name} = {round(total + lead_in + tail, 3)};\n")
    f.write("export type Line = { i: number; section: string; text: string; start: number; end: number };\n")
    f.write("export const LINES: Line[] = " + json.dumps(timing, ensure_ascii=False, indent=2) + ";\n")
print("lines", n, "pauses", len(sil), "speech", round(speech, 1), "s, total", round(total + lead_in + tail, 1))
for t in timing:
    print(f'{t["start"]:7.2f}-{t["end"]:7.2f} {t["text"][:40]}')
