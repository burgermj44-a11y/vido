"""Map transcribed pause-segments of an external narration to the script lines.

Usage: python3 match_segments.py <script_module> <segs_text.json> <timing_ts_out> <DURATION_NAME> <total_seconds> [tail]

segs_text.json: [[start, end, whisper_text], ...] in order. Every segment is
assigned to one script line (monotonic), maximizing character-bigram
similarity, so each line gets the real start/end of its words even when the
reader merges or splits sentences differently.
"""
import importlib
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
mod, segf, ts_out, dur_name, total = sys.argv[1:6]
tail = float(sys.argv[6]) if len(sys.argv) > 6 else 4.0
SCRIPT = importlib.import_module(mod).SCRIPT
segs = json.load(open(segf))


def norm(t):
    t = re.sub(r"[ً-ْـ]", "", t)
    t = re.sub("[إأآا]", "ا", t).replace("ة", "ه").replace("ى", "ي").replace("ؤ", "و").replace("ئ", "ي")
    t = re.sub(r"[^ء-ي0-9 ]", " ", t)
    return re.sub(r"\s+", " ", t).strip()


def grams(t):
    t = norm(t).replace(" ", "")
    return [t[i : i + 2] for i in range(len(t) - 1)]


lines = [grams(pl) for _, pl, _ in SCRIPT]
lens = [max(1, len(g)) for g in lines]
sg = [grams(s[2]) for s in segs]


def sim(seg_g, line_g):
    if not seg_g:
        return 0.0
    pool = {}
    for g in line_g:
        pool[g] = pool.get(g, 0) + 1
    hit = 0
    for g in seg_g:
        if pool.get(g, 0) > 0:
            hit += 1
            pool[g] -= 1
    return hit / len(seg_g)


n, m = len(lines), len(segs)
NEG = -1e18
# dp[j][i]: best score with segments[:j] assigned, segment j-1 on line i
dp = [[NEG] * n for _ in range(m + 1)]
bk = [[-1] * n for _ in range(m + 1)]
for i in range(n):
    dp[1][i] = sim(sg[0], lines[i]) * len(sg[0]) - (2.0 * i if i else 0)
for j in range(2, m + 1):
    s_g = sg[j - 1]
    for i in range(n):
        sc = sim(s_g, lines[i]) * len(s_g)
        best, arg = NEG, -1
        for k in range(max(0, i - 3), i + 1):  # stay on line, or move ahead (skipping up to 2 lines)
            v = dp[j - 1][k] - (3.0 * (i - k - 1) if i - k > 1 else 0)
            if v > best:
                best, arg = v, k
        dp[j][i], bk[j][i] = best + sc, arg
i = max(range(n), key=lambda q: dp[m][q] - 3.0 * (n - 1 - q))
assign = [0] * m
for j in range(m, 0, -1):
    assign[j - 1] = i
    i = bk[j][i]

timing = []
for li, (section, plain, _) in enumerate(SCRIPT):
    idx = [j for j in range(m) if assign[j] == li]
    if idx:
        a, b = segs[idx[0]][0], segs[idx[-1]][1]
    else:
        prev = timing[-1]["end"] if timing else 0.0
        a = b = prev
    timing.append({"i": li, "section": section, "text": plain, "start": round(a, 3), "end": round(b, 3)})
# lines the reader skipped get a short slot right after the previous line
for t in timing:
    if t["end"] - t["start"] < 0.05:
        t["end"] = round(t["start"] + 0.4, 3)
missing = [t["i"] for t in timing if not any(assign[j] == t["i"] for j in range(m))]
with open(ts_out, "w") as f:
    f.write("// Generated by scripts/match_segments.py - timing of the external narration (seconds).\n")
    f.write(f"export const {dur_name} = {round(float(total) + tail, 3)};\n")
    f.write("export type Line = { i: number; section: string; text: string; start: number; end: number };\n")
    f.write("export const LINES: Line[] = " + json.dumps(timing, ensure_ascii=False, indent=2) + ";\n")
print("segments", m, "lines", n, "lines with no audio:", missing)
for t in timing:
    print(f'{t["i"]:3d} {t["start"]:7.2f}-{t["end"]:7.2f} {t["text"][:45]}')
